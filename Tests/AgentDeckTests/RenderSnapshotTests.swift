/// 把“有数据”的界面渲染成 PNG（/tmp），供人工核对真实呈现。
/// 会话数据经 canonical Runtime v2 catalog + snapshot barrier 注入，无需真 daemon。
@MainActor
final class RenderSnapshotTests: XCTestCase {
  func testRenderHeader() throws {
    let model = try canonicalModel(
      items: [
        snapshotItem(
          "item-user-header",
          commandID: "command-header",
          item: .userMessage(
            text: "把登录模块拆分为独立 service，抽出 token 刷新逻辑，并补齐单元测试。",
            meta: RuntimeAgentItemMetaV1()
          )
