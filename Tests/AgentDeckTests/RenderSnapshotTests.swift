  func testRenderToolCallCollapsed() throws {
    let model = try canonicalModel(items: [toolCallItem(id: "item-tool-collapsed")])
    let item = try XCTUnwrap(model.selectedItems.first)
    let row = ConversationDisplayRow(
      role: .assistantItem,
      turnId: "turn-render",
      item: item,
      firstInTurn: true,
      lastInTurn: true
    )
    let cell = ToolCallCellView()
    cell.wantsLayer = true
    cell.layer?.backgroundColor = DesignTokens.bg.cgColor
    let width: CGFloat = 620
    let height = ConversationRowFactory.height(for: row, width: width) + 6
    cell.translatesAutoresizingMaskIntoConstraints = false
    cell.widthAnchor.constraint(equalToConstant: width).isActive = true
    cell.heightAnchor.constraint(equalToConstant: height).isActive = true
    cell.configure(row: row, width: width, model: model)
    cell.layoutSubtreeIfNeeded()
    cell.renderPNG(to: "/tmp/adk-toolcall.png")
  }

