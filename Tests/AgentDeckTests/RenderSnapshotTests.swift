  private func canonicalModel(
    conversationID: RuntimeConversationID = RuntimeConversationID(
      rawValue: "conversation-render"
    ),
    cwd: String = "/p/refactor-auth",
    items: [SnapshotItemV1]
  ) throws -> SessionModel {
    let model = SessionModel()
    model.cwd = URL(fileURLWithPath: cwd)
    try model.workbench.installCatalog(
      snapshotPages: [
        try RuntimeCatalogSnapshotV2(
          baseCatalogCursor: .beforeFirst,
          entries: [
            RuntimeConversationEntryV2(
              conversationID: conversationID,
              agentKind: .codex,
              title: "Refactor auth",
              cwd: cwd,
              lastActiveMs: 1_000,
              archived: false,
              entryRevision: 1
            )
          ],
          nextPageCursor: nil
        )
      ]
    )
    let snapshot = try ConversationSnapshotV2(
      conversationID: conversationID,
      baseEventCursor: .beforeFirst,
      configurationState: try RuntimeConversationConfigurationStateV2(
        configurationRevision: 0,
        configuration: nil
      ),
      items: [.capabilities(try capabilities())] + items
    )
    _ = try model.workbench.ingest(.synchronizedReply(.snapshot(snapshot)))
    _ = try model.workbench.ingest(
      .synchronizedReply(
        .syncComplete(try syncComplete(conversationID: conversationID))
      )
    )
    try model.workbench.selectConversation(conversationID)
    return model
  }

  private func snapshotItem(
    _ id: String,
    commandID: String?,
    item: RuntimeAgentItemV1
  ) -> SnapshotItemV1 {
    .item(
      itemID: RuntimeItemID(rawValue: id),
      entityID: RuntimeEntityID(rawValue: "entity-\(id)"),
      commandID: commandID.map(RuntimeCommandID.init(rawValue:)),
      item: item
    )
  }

  private func toolCallItem(
    id: String,
    commandID: String = "command-tool"
  ) -> SnapshotItemV1 {
    snapshotItem(
      id,
      commandID: commandID,
      item: .toolCall(
        name: "TaskCreate",
        args: AnyCodable([
          "activeForm": "收录厂家摄像头资料",
          "subject": "收录厂家参数",
          "description": "把资料收进当前仓库",
        ]),
        result: AnyCodable(["status": "completed"]),
        meta: RuntimeAgentItemMetaV1()
      )
    )
  }

  private func capabilities() throws -> RuntimeSessionCapabilitiesV1 {
    try decode(
      RuntimeSessionCapabilitiesV1.self,
      [
        "agentKind": "codex",
        "agentVersion": "test",
        "features": ["streamingMessages", "streamingReasoning"],
        "vendor": [
          "agentKind": "codex",
          "sandboxModes": ["workspace-write"],
          "persistenceSupported": false,
          "reasoningEffortLevels": ["medium"],
        ],
      ]
    )
  }

  private func syncComplete(
    conversationID: RuntimeConversationID
  ) throws -> RuntimeSyncCompleteV1 {
    try decode(
      RuntimeSyncCompleteV1.self,
      [
        "streamGeneration": "fixture-generation",
        "streamCursor": "beforeFirst",
        "innerCursor": [
          "scope": "conversation",
          "conversationId": conversationID.rawValue,
          "cursor": "beforeFirst",
        ],
        "keyDirectoryRevision": 0,
      ]
    )
  }

  private func decode<Value: Decodable>(_ type: Value.Type, _ object: Any) throws -> Value {
    let data = try JSONSerialization.data(withJSONObject: object, options: [.sortedKeys])
    return try JSONDecoder().decode(type, from: data)
  }
}
